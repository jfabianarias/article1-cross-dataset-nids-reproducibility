#!/usr/bin/env python3
"""Reconstructed five-seed joint *within-direction* paired class-stratified bootstrap.

Each resampled flow contributes the same shared index to all 4 classifiers and
5 fixed seeds. For balanced accuracy, mean across models and seeds is linear
in per-flow correctness; compressing that correctness to a 0..20 histogram
produces an EXACT distributionally equivalent nonparametric bootstrap without
materializing huge sampled index matrices. Resamples are class-stratified and
preserve benign/attack counts. CIs are percentile 2.5/97.5. No use of target
labels for training; uncertainty is conditional on the fixed held-out flows,
not session/host-cluster robust or a replication of historical RNG draws.
"""
import argparse,hashlib,json,platform,sys
from pathlib import Path
import numpy as np,pandas as pd
SOURCES=['UNSW_NB15','CICIDS2017','BoT_IoT','TON_IoT']
MODELS=['Linear SVM','XGBoost','Random Forest','MLP']
SEEDS=[42,52,62,72,82]

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--private',type=Path,required=True);ap.add_argument('--archive',type=Path,required=True);ap.add_argument('--out',type=Path,required=True);ap.add_argument('--replicates',type=int,default=2000);ap.add_argument('--rng-seed',type=int,default=20261105);a=ap.parse_args();a.out.mkdir(parents=True,exist_ok=True)
 ref=pd.read_csv(a.archive).set_index(['source','target','model','seed']);rng=np.random.default_rng(a.rng_seed)
 rows=[];validation=[]
 for target in SOURCES:
  reference_y=None;reference_idx=None
  for src in SOURCES:
   preds=[]
   for model in MODELS:
    for seed in SEEDS:
     f=a.private/f'{src}__{model.replace(" ","_")}__s{seed}__{target}.npz'
     if not f.exists():raise FileNotFoundError(f)
     with np.load(f,allow_pickle=False) as z:
      y=z['y_true'].astype(np.int8); idx=z['target_test_index'];p=z['y_pred'].astype(np.int8)
     if reference_y is None: reference_y=y.copy();reference_idx=idx.copy()
     if not (np.array_equal(y,reference_y) and np.array_equal(idx,reference_idx)):raise ValueError(f'unaligned labels/index: {f}')
     tn=int(np.sum((y==0)&(p==0)));fp=int(np.sum((y==0)&(p==1)));fn=int(np.sum((y==1)&(p==0)));tp=int(np.sum((y==1)&(p==1)))
     if not all(int(ref.loc[(src,target,model,seed),k])==v for k,v in zip(['tn','fp','fn','tp'],[tn,fp,fn,tp])):raise ValueError(f'matrix mismatch {f}')
     preds.append(p)
   mat=np.stack(preds,axis=0);n_pred=len(preds)
   # P(positive) per flow among the 20 fixed model/seed predictors
   sum_pos=np.sum(mat,axis=0).astype(np.int16)
   n0=int((reference_y==0).sum());n1=int((reference_y==1).sum())
   h0=np.bincount(sum_pos[reference_y==0],minlength=n_pred+1)
   h1=np.bincount(sum_pos[reference_y==1],minlength=n_pred+1)
   assert h0.sum()==n0 and h1.sum()==n1
   k=np.arange(n_pred+1,dtype=np.float64)/n_pred
   mean_benign=1-(h0@k)/n0;mean_attack=(h1@k)/n1
   ba=0.5*(mean_benign+mean_attack)
   h0_draw=rng.multinomial(n0,h0/n0,size=a.replicates)
   h1_draw=rng.multinomial(n1,h1/n1,size=a.replicates)
   samples=0.5*(1-(h0_draw@k)/n0+(h1_draw@k)/n1)
   ci=np.quantile(samples,[.025,.975]);grp=ref.loc[(src,target)]
   ba_archive=0.5*(grp.tp/(grp.tp+grp.fn)+grp.tn/(grp.tn+grp.fp)).mean()
   assert abs(ba-ba_archive)<1e-12,(src,target,ba,ba_archive)
   rows.append(dict(source=src,target=target,BA=ba,ci_low=ci[0],ci_high=ci[1],ci_half_width=(ci[1]-ci[0])/2,n_seeds=5,n_models=4,n_samples=n0+n1,n_benign=n0,n_attack=n1,replicates=a.replicates,rng_seed=a.rng_seed,estimand='fixed 5 seeds; paired 20 predictors; stratified flow bootstrap'))
   validation.append(dict(source=src,target=target,archive_BA=ba_archive,reconstructed_BA=ba,max_abs_BA_error=abs(ba_archive-ba),label_alignment=True,all_20_confusion_matrices_exact=True))
   print(src,'->',target,'BA',round(100*ba,3),'CI',tuple(np.round(100*ci,3)),flush=True)
 pd.DataFrame(rows).to_csv(a.out/'Figure2_five_seed_paired_flow_2000_CI.csv',index=False,float_format='%.12g')
 pd.DataFrame(validation).to_csv(a.out/'Figure2_16_alignment_and_counts_validation.csv',index=False)
 (a.out/'METHOD.md').write_text('''# Independently specified five-seed paired-flow bootstrap\n\nAll 320 per-evaluation NPZ predictions were generated by retraining the frozen source-only benchmark on the four harmonized datasets. Each regenerated TN/FP/FN/TP exactly matched the archived counts. For a particular source-target direction, each target test row is aligned by positional index across four models and five fixed seeds. We compute the mean correctness on every flow over the 20 predictors. Within each true class, we sample with replacement the original number of flows; the same sampled flow contributes simultaneously to all 20 predictors. Balanced accuracy in each bootstrap sample is half the average per-flow correctness for benign plus half the average for attacks. We apply 2,000 stratified nonparametric percentile replicates with RNG seed 20261105. The categorical multinomial draw on the integer count of positive predictions (0..20) is mathematically distributionally equivalent for this statistic to sampling shared per-flow indices; the compression is exact, not a Gaussian approximation. Each direction marginal CI is computed separately; pairwise differences of two different training-source directions are *not* inferred from those separate intervals. This is a NEW, FULLY REPRODUCIBLE 5-seed flow bootstrap, NOT a bit-for-bit recreation of unknown historical 2,000 RNG draws. It is conditional on the fixed test partitions and five seeds, not host/session clustered, so no population-level/generalized significance claims. Indices are positional, not original physical-flow IDs.\n''')
 metadata=dict(replicates=a.replicates,rng_seed=a.rng_seed,method='class-stratified nonparametric flow bootstrap; 20 matched predictor votes per direction',n_files=320,n_directions=16,python=sys.version.split()[0],numpy=np.__version__,pandas=pd.__version__,platform=platform.platform())
 (a.out/'run_metadata.json').write_text(json.dumps(metadata,indent=2))
if __name__=='__main__':main()
